#!/usr/bin/env node
// Lists every HTTP route the gateway exposes, with the guards and roles that protect it,
// read from the controllers' decorators. For a penetration tester ("what is the attack
// surface?") and for a SOC 2 auditor ("show me the access-control matrix"): both are
// otherwise answered by reading forty files.
//
//   node scripts/route-inventory.js            markdown table on stdout
//   node scripts/route-inventory.js --check    exit 1 if any route has no guard (for CI)
//
// It reads source, not the running app, so it sees decorators as written. What it cannot
// see: guards applied globally in main.ts, and middleware. Those are listed at the end.
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, '..', 'src');
const files = [];
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p);
    else if (/\.controller\.ts$/.test(e.name)) files.push(p);
  }
})(SRC);

const routes = [];
for (const f of files.sort()) {
  const text = fs.readFileSync(f, 'utf8');
  const classRe = /((?:@\w+(?:\([^)]*\))?\s*)+)export class (\w+)/g;
  let m;
  while ((m = classRe.exec(text))) {
    const deco = m[1];
    if (!/@Controller/.test(deco)) continue;
    const prefix = (deco.match(/@Controller\(\s*['"`]([^'"`]*)['"`]/) || [, ''])[1];
    const classGuards = [...deco.matchAll(/@UseGuards\(([^)]*)\)/g)].map((x) => x[1].replace(/\s+/g, ' ')).join(', ');
    // Up to the next class: a file may hold more than one controller.
    const rest = text.slice(m.index + m[0].length);
    const next = rest.search(/\n(?:@\w+(?:\([^)]*\))?\s*)+export class /);
    const body = next === -1 ? rest : rest.slice(0, next);
    const methodRe = /((?:\s*@\w+(?:\([^)]*\))?)+)\s*(?:async\s+)?(\w+)\s*\(/g;
    let mm;
    while ((mm = methodRe.exec(body))) {
      const d = mm[1];
      const verb = d.match(/@(Get|Post|Put|Patch|Delete)\(\s*(?:['"`]([^'"`]*)['"`])?\s*\)/);
      if (!verb) continue;
      const guards = [...d.matchAll(/@UseGuards\(([^)]*)\)/g)].map((x) => x[1].replace(/\s+/g, ' ')).join(', ');
      const roles = (d.match(/@RequireTenantRole\(([^)]*)\)/) || [, ''])[1].replace(/\.\.\./g, '').trim();
      const pub = /@Public\(\)/.test(d);
      routes.push({
        method: verb[1].toUpperCase(),
        path: '/' + [prefix, verb[2] || ''].filter(Boolean).join('/').replace(/\/+/g, '/').replace(/^\//, ''),
        guards: [classGuards, guards].filter(Boolean).join(', ') || (pub ? '(public)' : '— none —'),
        roles: roles || '',
        handler: `${path.relative(SRC, f)}:${mm[2]}`,
      });
    }
  }
}

// Routes that carry no guard decorator on purpose, and why. A new route with no guard is
// an error until it is added here with a reason somebody reviewed.
const PUBLIC = [
  [/^\/auth\/sso\//, 'the sign-in flow itself (WorkOS / OIDC redirect and callback); state and PKCE protect it'],
  [/^\/v1\/auth\/(login|register|mfa\/verify)$/, 'sign-in endpoints, rate-limited per client (5-10 requests a minute)'],
  [/^\/console(\/|$)/, 'the console\'s static shell and fonts; every API call it makes needs a JWT'],
  [/^\/dashboard(\/|$)/, 'read-only dashboard: a signed session cookie is checked inside each handler (readSession), signed in with an API key'],
  [/^\/health(\/ready)?$/, 'liveness and readiness probes'],
  [/^\/metrics$/, 'Prometheus scrape; protected by a bearer token when METRICS_TOKEN is set (chart: metrics.tokenSecret)'],
];
const reasonFor = (r) => { const p = PUBLIC.find(([re]) => re.test('/' + r.path.replace(/^\//, ''))); return p ? p[1] : null; };
for (const r of routes) if (r.guards === '— none —' && reasonFor(r)) r.guards = '(public)';

routes.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));
const unguarded = routes.filter((r) => r.guards === '— none —');
const publicRoutes = routes.filter((r) => r.guards === '(public)');

if (process.argv.includes('--check')) {
  if (unguarded.length) {
    console.error(`${unguarded.length} route(s) with no guard decorator and no recorded reason (add a guard, or a reason in PUBLIC):`);
    for (const r of unguarded) console.error(`  ${r.method} /${r.path.replace(/^\//, '')}  (${r.handler})`);
    process.exit(1);
  }
  console.log(`all ${routes.length} routes are guarded or deliberately public (${publicRoutes.length})`);
  process.exit(0);
}

console.log('# Gateway route inventory\n');
console.log(`Generated by \`node scripts/route-inventory.js\` from controller decorators. ${routes.length} routes; ${publicRoutes.length} deliberately public; ${unguarded.length} with no guard decorator and no recorded reason.\n`);
console.log('| Method | Path | Guards | Roles | Handler |\n|---|---|---|---|---|');
for (const r of routes) console.log(`| ${r.method} | \`/${r.path.replace(/^\//, '')}\` | ${r.guards.replace(/\|/g, '\\|')} | ${r.roles.replace(/\|/g, '\\|')} | \`${r.handler}\` |`);
console.log('\n## Deliberately public routes, and why\n');
for (const [re, why] of PUBLIC) console.log(`- \`${re.source.replace(/\\\//g, '/')}\` — ${why}`);
console.log('\nNot visible to this tool: guards or middleware applied globally in `src/main.ts`, rate limiting, and the TRISA gRPC listener (a separate port, see docs/deployment/TRISA.md).');
