#!/usr/bin/env node
// Compiles contracts/PermissionedToken.sol and writes the result where the gateway reads it:
// src/tokenisation/permissioned-token.artifact.ts.
//
//   node scripts/build-contracts.js          write it
//   node scripts/build-contracts.js --check  fail if the committed artifact is not what this
//                                            source compiles to (run by the tests and CI, so
//                                            the contract the gateway verifies against can
//                                            never drift from the source people audit)
//
// The artifact records the SHA-256 of the source and the compiler version it was built with.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const solc = require('solc');

const SRC = path.join(__dirname, '..', '..', '..', 'contracts', 'PermissionedToken.sol');
const OUT = path.join(__dirname, '..', 'src', 'tokenisation', 'permissioned-token.artifact.ts');

function compile() {
  const source = fs.readFileSync(SRC, 'utf8');
  const input = {
    language: 'Solidity',
    sources: { 'PermissionedToken.sol': { content: source } },
    settings: { optimizer: { enabled: true, runs: 200 }, evmVersion: 'paris', outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'evm.deployedBytecode.immutableReferences'] } } },
  };
  const out = JSON.parse(solc.compile(JSON.stringify(input)));
  const errors = (out.errors || []).filter((e) => e.severity === 'error');
  if (errors.length) throw new Error(errors.map((e) => e.formattedMessage).join('\n'));
  const c = out.contracts['PermissionedToken.sol'].PermissionedToken;
  return {
    sourceSha256: crypto.createHash('sha256').update(source).digest('hex'),
    compiler: solc.version(),
    abi: c.abi,
    bytecode: '0x' + c.evm.bytecode.object,
    // What the deployed contract's code should be, and where the compiler patches in the
    // constructor's immutables (decimals, supplyCap): those bytes differ per deployment
    // and are masked when a deployed contract is compared against this.
    deployedBytecode: '0x' + c.evm.deployedBytecode.object,
    immutableReferences: Object.values(c.evm.deployedBytecode.immutableReferences || {}).flat(),
  };
}

function render(a) {
  return `// GENERATED by scripts/build-contracts.js from contracts/PermissionedToken.sol -- do not edit.
// \`node scripts/build-contracts.js --check\` fails if this is not what the source compiles to.
export const PERMISSIONED_TOKEN = ${JSON.stringify(a, null, 2)} as const;
`;
}

if (require.main === module) {
  const a = compile();
  const text = render(a);
  if (process.argv.includes('--check')) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (have !== text) { console.error('permissioned-token.artifact.ts is out of date: run node scripts/build-contracts.js'); process.exit(1); }
    console.log('artifact matches source', a.sourceSha256.slice(0, 12), a.compiler);
  } else {
    fs.writeFileSync(OUT, text);
    console.log('wrote', path.relative(process.cwd(), OUT), a.sourceSha256.slice(0, 12), a.compiler);
  }
}
module.exports = { compile, render };
